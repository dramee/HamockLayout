#pragma once

#include "hammock/graph.hpp"

#include <vector>

// Выделение гамаков в ориентированном графе по статье
// В. Н. Касьянов, «Выделение гамаков в ориентированном графе»,
// Доклады АН СССР, 1975, т. 221, № 5, с. 1020–1022.
//
// Граф программы G = (X, Г): выделены вход и выход, нет дуг, заходящих во вход
// или исходящих из выхода, через любую вершину проходит путь от входа к выходу.
//
// Непустое множество U ⊆ X образует гамак с начальной вершиной p ∈ U
// и конечной вершиной q ∉ U, если
//     Г^-1(U \ {p}) ⊆ U,   Г(U) \ U = {q}   и   p ∉ Г(q).
//
// Уточнения, неявно используемые в статье (без них неверна лемма 4):
//   * выход графа не принадлежит U. Иначе, например, в графе
//     entry→h, h→x, x→y, y→h, h→exit множество {h, exit} формально удовлетворяет
//     условиям с p = h, q = x, хотя управление из него не обязано попадать в q.
//     С этим условием U ∪ {q} — сам граф программы с входом p и выходом q;
//   * если вход графа лежит в U, то p — вход (у входа нет предшественников,
//     поэтому формально началом можно было бы назвать и другую вершину U).
// Оба алгоритма ниже перечисляют гамаки именно в этом смысле.
namespace hammock {

// Нумерации вершин из статьи. Все номера — от 1 до n, индекс вектора — вершина.
struct Numbering {
    // M-номера: порядок включения вершин в путь (прямой порядок обхода в глубину из входа).
    std::vector<int> M;
    // N-номера: порядок, обратный порядку удаления вершин из пути
    // (обратный порядок выхода из обхода в глубину).
    std::vector<int> N;
    // L-номера: результат n перенумераций относительно вершин p с L-номером 1, 2, ..., n.
    std::vector<int> L;
    // byL[k - 1] — вершина с L-номером k.
    std::vector<int> byL;
};

// Вычисляет M-, N- и L-нумерации. Граф должен быть графом программы.
// M и N — за O(m), L — за O(n·m) действий.
Numbering computeNumbering(const Graph& g);

// Гамак в компактном виде. По лемме 4 вершины гамака имеют подряд идущие
// L-номера Lp, Lp + 1, ..., Lp + size - 1.
struct HammockSpan {
    int start;  // начальная вершина p
    int end;    // конечная вершина q
    int size;   // |U|
};

// Гамак с явным списком вершин (вершины упорядочены по возрастанию индекса).
struct Hammock {
    int start;
    int end;
    std::vector<int> vertices;

    friend bool operator==(const Hammock& a, const Hammock& b) {
        return a.start == b.start && a.end == b.end && a.vertices == b.vertices;
    }
    friend bool operator<(const Hammock& a, const Hammock& b) {
        if (a.start != b.start) return a.start < b.start;
        if (a.end != b.end) return a.end < b.end;
        return a.vertices < b.vertices;
    }
};

struct HammockResult {
    Numbering numbering;
    // Гамаки упорядочены по L-номеру начальной вершины, затем по размеру.
    std::vector<HammockSpan> spans;

    // Вершины гамака в порядке L-номеров.
    std::vector<int> members(const HammockSpan& span) const;
    // Все гамаки с явными множествами вершин, в каноническом порядке.
    std::vector<Hammock> hammocks() const;
};

// Алгоритм теоремы 2: перечисляет все гамаки графа программы за O(n·m) действий
// (не считая вывода вершин гамаков). Проверяет граф и бросает GraphError,
// если он не является графом программы.
HammockResult findHammocks(const Graph& g);

// Эталонный алгоритм за O(n²·m), напрямую следующий определению: для каждой
// пары (p, q) кандидат U — множество вершин, достижимых из p без прохода через q.
// Используется для проверки быстрого алгоритма.
std::vector<Hammock> findHammocksReference(const Graph& g);

// Проверяет определение гамака для множества U с начальной вершиной p
// и конечной q дословно по статье, без уточнений, описанных выше.
bool isHammock(const Graph& g, const std::vector<int>& U, int p, int q);

// Сортирует гамаки и вершины внутри них в канонический порядок.
std::vector<Hammock> canonical(std::vector<Hammock> hammocks);

}  // namespace hammock
